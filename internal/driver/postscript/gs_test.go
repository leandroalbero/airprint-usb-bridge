// TestGhostscriptRendersInput runs the documents through a real PostScript interpreter: each page
// rendered at 300 dpi to PBM must be exactly the bitmap the driver encoded.
func TestGhostscriptRendersInput(t *testing.T) {
	gs, err := exec.LookPath("gs")
	if err != nil {
		t.Skip("gs (Ghostscript) not on PATH")
	}
	for _, c := range []struct {
		name  string
		opts  map[string]string
		media string
	}{
		{"level2-ascii85-a4", nil, "a4"},
		{"level2-binary-letter", map[string]string{"encoding": "binary"}, "letter"},
		{"level3-ascii85-a5", map[string]string{"level": "3"}, "a5"},
		{"level3-binary-pjl-duplex-legal", map[string]string{"level": "3", "encoding": "binary", "pjl": "true", "duplex": "true"}, "legal"},
	} {
		t.Run(c.name, func(t *testing.T) {
			d := newDriver(t, c.opts, driver.Config{Media: c.media})
			job := drivertest.Job(t, d.Capabilities())
			job.Name = "gs (test) \\ page"
			job.Sides = "two-sided-long-edge"
			pages := []raster.Page{textPage(job.Media), photoPage(job.Media), drivertest.SheetPage(job.Media, 300, 0)}
			var want []*imaging.Bitmap
			for _, p := range pages {
				sheet, err := imaging.Place(p, job.Media, imaging.PlaceOptions{XDPI: 300, YDPI: 300})
				if err != nil {
					t.Fatal(err)
				}
				bm, _, err := imaging.Binarize(sheet, "")
				if err != nil {
					t.Fatal(err)
				}
				want = append(want, bm)
			}
			units, err := d.Render(context.Background(), job, pages)
			if err != nil {
				t.Fatal(err)
			}
			data := units[0].Data
			if c.opts["pjl"] == "true" {
				// Ghostscript does not read PJL; a printer strips it before the interpreter.
				start := bytes.Index(data, []byte("%!PS-Adobe-3.0"))
				end := bytes.LastIndex(data, []byte("%%EOF\n")) + len("%%EOF\n")
				data = data[start:end]
			}
			dir := t.TempDir()
			in := filepath.Join(dir, "job.ps")
			if err := os.WriteFile(in, data, 0o644); err != nil {
				t.Fatal(err)
			}
			cmd := exec.Command(gs, "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE", "-sDEVICE=pbmraw", "-r300",
				"-sOutputFile="+filepath.Join(dir, "p%d.pbm"), in)
			if out, err := cmd.CombinedOutput(); err != nil || len(bytes.TrimSpace(out)) > 0 {
				t.Fatalf("gs: %v\n%s", err, out)
			}
			for i, bm := range want {
				got, err := readPBM(filepath.Join(dir, fmt.Sprintf("p%d.pbm", i+1)))
				if err != nil {
					t.Fatal(err)
				}
				if got.W != bm.W || got.H != bm.H {
					t.Fatalf("page %d: gs rendered %dx%d, sent %dx%d", i+1, got.W, got.H, bm.W, bm.H)
				}
				if diff := countDiff(got, bm); diff != 0 {
					t.Errorf("page %d: %d dots differ from the input bitmap (%d black sent)", i+1, diff, bm.Ink())
				}
			}
			if _, err := os.Stat(filepath.Join(dir, fmt.Sprintf("p%d.pbm", len(want)+1))); err == nil {
				t.Errorf("gs rendered more than %d pages", len(want))
			}
		})
	}
}

// photoPage is a gradient with a dark disc, so auto mode dithers it.
func photoPage(m driver.Media) raster.Page {
	w := (m.Width*300 + 1270) / 2540
	h := (m.Length*300 + 1270) / 2540
	return drivertest.Page(w, h, 300, func(x, y int) byte {
		dx, dy := x-w/2, y-h/2
		if dx*dx+dy*dy < 300*300 {
			return 30
		}
		return byte((x + y) * 255 / (w + h))
	})
}

func readPBM(path string) (*imaging.Bitmap, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	return parsePBM(data)
}

// parsePBM reads a raw (P4) PBM, including the comment lines Ghostscript writes in the header.
func parsePBM(data []byte) (*imaging.Bitmap, error) {
	if !bytes.HasPrefix(data, []byte("P4")) {
		return nil, fmt.Errorf("not a raw PBM")
	}
	i := 2
	var dims [2]int
	for k := range dims {
		for i < len(data) && (data[i] == '#' || data[i] == ' ' || data[i] == '\t' || data[i] == '\r' || data[i] == '\n') {
			if data[i] == '#' {
				for i < len(data) && data[i] != '\n' {
					i++
				}
				continue
			}
			i++
		}
		start := i
		for i < len(data) && data[i] >= '0' && data[i] <= '9' {
			dims[k] = dims[k]*10 + int(data[i]-'0')
			i++
		}
		if i == start || dims[k] <= 0 || dims[k] > 1<<16 {
			return nil, fmt.Errorf("PBM header: bad dimension at byte %d", start)
		}
	}
	i++
	bm := imaging.NewBitmap(dims[0], dims[1])
	if i > len(data) || len(data)-i != len(bm.Pix) {
		return nil, fmt.Errorf("PBM: %d bytes of samples, want %d", len(data)-i, len(bm.Pix))
	}
	copy(bm.Pix, data[i:])
	return bm, nil
}

func TestParsePBM(t *testing.T) {
	data := append([]byte("P4\n# Image generated by GPL Ghostscript (device=pbmraw)\n16 2\n"), 0x80, 0x01, 0xff, 0x00)
	bm, err := parsePBM(data)
	if err != nil {
		t.Fatal(err)
	}
	if bm.W != 16 || bm.H != 2 || !bm.At(0, 0) || !bm.At(15, 0) || bm.At(1, 0) || !bm.At(7, 1) || bm.At(8, 1) {
		t.Fatalf("parsed %+v", bm)
	}
	if _, err := parsePBM(data[:len(data)-1]); err == nil {
		t.Fatal("short PBM accepted")
	}
	if _, err := parsePBM([]byte("P1\n1 1\n0")); err == nil {
		t.Fatal("plain PBM accepted")
	}
}

func countDiff(a, b *imaging.Bitmap) int {
	n := 0
	for y := 0; y < a.H; y++ {
		for x := 0; x < a.W; x++ {
			if a.At(x, y) != b.At(x, y) {
				n++
			}
		}
	}
	return n
}

// TestGhostscriptRendersColor runs colour documents through Ghostscript: each RGB page rendered
// at 300 dpi to PPM must be exactly the sheet the driver placed, and a gray page in the same
// document the bitmap it encoded.
func TestGhostscriptRendersColor(t *testing.T) {
	gs, err := exec.LookPath("gs")
	if err != nil {
		t.Skip("gs (Ghostscript) not on PATH")
	}
	for _, c := range []struct {
		name string
		opts map[string]string
	}{
		{"level2-ascii85", nil},
		{"level2-binary", map[string]string{"encoding": "binary"}},
		{"level3-ascii85", map[string]string{"level": "3"}},
		{"level3-binary-depth8", map[string]string{"level": "3", "encoding": "binary", "depth": "8"}},
	} {
		t.Run(c.name, func(t *testing.T) {
			d := newDriver(t, c.opts, driver.Config{Color: "on", Media: "a5"})
			job := drivertest.Job(t, d.Capabilities())
			pages := []raster.Page{rgbChart(job.Media, 300, false), textPage(job.Media), rgbChart(job.Media, 300, true)}
			var want [][]byte
			for _, p := range pages {
				sheet, err := imaging.Place(p, job.Media, imaging.PlaceOptions{XDPI: 300, YDPI: 300})
				if err != nil {
					t.Fatal(err)
				}
				var rgb []byte
				switch {
				case sheet.RGB != nil:
					rgb = sheet.RGB
				case d.set.Depth == 8:
					for _, v := range sheet.Gray {
						rgb = append(rgb, v, v, v)
					}
				default:
					bm, _, _ := imaging.Binarize(sheet, "")
					for y := 0; y < bm.H; y++ {
						for x := 0; x < bm.W; x++ {
							v := byte(255)
							if bm.At(x, y) {
								v = 0
							}
							rgb = append(rgb, v, v, v)
						}
					}
				}
				want = append(want, rgb)
			}
			units, err := d.Render(context.Background(), job, pages)
			if err != nil {
				t.Fatal(err)
			}
			dir := t.TempDir()
			in := filepath.Join(dir, "job.ps")
			if err := os.WriteFile(in, units[0].Data, 0o644); err != nil {
				t.Fatal(err)
			}
			cmd := exec.Command(gs, "-q", "-dSAFER", "-dBATCH", "-dNOPAUSE", "-sDEVICE=ppmraw", "-r300",
				"-sOutputFile="+filepath.Join(dir, "p%d.ppm"), in)
			if out, err := cmd.CombinedOutput(); err != nil || len(bytes.TrimSpace(out)) > 0 {
				t.Fatalf("gs: %v\n%s", err, out)
			}
			for i, w := range want {
				data, err := os.ReadFile(filepath.Join(dir, fmt.Sprintf("p%d.ppm", i+1)))
				if err != nil {
					t.Fatal(err)
				}
				gw, gh, pix, err := parsePPM(data)
				if err != nil {
					t.Fatal(err)
				}
				if gw*gh*3 != len(w) {
					t.Fatalf("page %d: gs rendered %dx%d, sent %d bytes", i+1, gw, gh, len(w))
				}
				diff := 0
				for k := range w {
					if pix[k] != w[k] {
						diff++
					}
				}
				if diff != 0 {
					t.Errorf("page %d: %d samples differ", i+1, diff)
				}
			}
			if _, err := os.Stat(filepath.Join(dir, fmt.Sprintf("p%d.ppm", len(want)+1))); err == nil {
				t.Errorf("gs rendered more than %d pages", len(want))
			}
		})
	}
}

// parsePPM reads a raw (P6) 8-bit PPM, including Ghostscript's comment lines.
func parsePPM(data []byte) (w, h int, pix []byte, err error) {
	if !bytes.HasPrefix(data, []byte("P6")) {
		return 0, 0, nil, fmt.Errorf("not a raw PPM")
	}
	i := 2
	var v [3]int
	for k := range v {
		for i < len(data) && (data[i] == '#' || data[i] == ' ' || data[i] == '\t' || data[i] == '\r' || data[i] == '\n') {
			if data[i] == '#' {
				for i < len(data) && data[i] != '\n' {
					i++
				}
				continue
			}
			i++
		}
		start := i
		for i < len(data) && data[i] >= '0' && data[i] <= '9' {
			v[k] = v[k]*10 + int(data[i]-'0')
			i++
		}
		if i == start || v[k] <= 0 || v[k] > 1<<16 {
			return 0, 0, nil, fmt.Errorf("PPM header: bad value at byte %d", start)
		}
	}
	i++
	if v[2] != 255 || len(data)-i != 3*v[0]*v[1] {
		return 0, 0, nil, fmt.Errorf("PPM: maxval %d, %d bytes of samples for %dx%d", v[2], len(data)-i, v[0], v[1])
	}
	return v[0], v[1], data[i:], nil
}
